const { test } = require('node:test');
const assert = require('node:assert/strict');
const { createCore } = require('../core/api');
const { passwords } = require('../backend/platform');
const { database } = require('./helpers');

test('postgres: existing workflow and permission regression', async () => {
  const db = await database();
  const platform = { ...passwords, mailConfigured: async () => false, supportsLoginCodes: true };
  const core = await db.withConnection(() => createCore({ db, platform }));
  const call = (method, path, body = {}, token = null, query = {}) => db.withConnection(() => core.handle({ method, path, body, token, query }), { readOnly: core.isReadOnly(method, path) });
  const good = async (...args) => { const result = await call(...args); assert.equal(result.status, 200, `${args[0]} ${args[1]}: ${JSON.stringify(result.body)}`); return result.body; };
  try {
    const password = 'integration-password';
    await db.withConnection(async () => db.prepare('UPDATE users SET password_hash = ? WHERE id = 1').run(await passwords.hashPassword(password)));
    const admin = (await good('POST', '/api/login', { email: 'BHAVESH122000@gmail.com', password }))._session;
    const employee = await good('POST', '/api/users', { name: 'Employee', email: 'employee@example.com', password }, admin);
    const staff = (await good('POST', '/api/login', { email: employee.email, password }))._session;
    assert.equal((await call('POST', '/api/users', { name: 'No', email: 'no@example.com', password }, staff)).status, 403);
    await good('POST', '/api/users', { name: 'Second admin', email: 'second@example.com', password, role: 'admin' }, admin);
    assert.equal((await good('GET', '/api/users', {}, admin)).length, 3);
    assert.equal((await call('POST', '/api/setup', { name: 'No', email: 'no@example.com', password })).status, 400);
    const library = await good('GET', '/api/library', {}, admin);
    assert.equal(library.checklists.length, 6);
    assert.equal((await good('GET', '/api/library', {}, staff)).checklists.some(c => c.area === 'tax'), false);
    const matter = await good('POST', '/api/matters', { code: 'BC2001', client: 'Case client', type: 'P', settlement_date: '2027-01-29', unconditional: true }, admin);
    const detail = await good('GET', `/api/matters/${matter.id}`, {}, admin);
    assert.ok(detail.stages.length > 0); assert.ok(detail.milestones.length > 0);
    assert.equal((await call('POST', '/api/matters', { code: 'bc2001', type: 'P' }, admin)).status, 400);
    const tasks = await good('GET', '/api/tasks', {}, admin);
    assert.ok(tasks.some(t => t.title.startsWith('UNFIN')));
    const task = await good('POST', '/api/tasks', { title: 'Review title', matter_id: matter.id, assignee_id: employee.id, due_date: '2027-01-25', due_time: '09:00', duration: 60, checklist: ['First check', 'Second check'], repeat: 'weekly' }, admin);
    assert.equal(task.checklist.length, 2);
    await good('PUT', `/api/tasks/${task.id}`, { status: 'done' }, admin);
    assert.ok((await good('GET', '/api/tasks', {}, admin)).some(t => t.series_id === task.id));
    const copy = await good('POST', `/api/tasks/${task.id}/copy`, { due_date: '2027-01-26' }, admin);
    assert.equal(copy.checklist.length, 2);
    const tax = await good('POST', '/api/matters', { code: 'TAX2001', type: 'TAX', client: 'Private tax job' }, admin);
    assert.equal((await call('GET', `/api/matters/${tax.id}`, {}, staff)).status, 403);
    assert.equal((await good('GET', '/api/matters', {}, staff)).some(m => m.id === tax.id), false);
    assert.equal((await call('POST', '/api/tasks', { title: 'Private', matter_id: tax.id, assignee_id: employee.id }, admin)).status, 400);
    const callback = await good('POST', '/api/callbacks', { caller_name: 'Alex', phone: '1234', assignee_id: employee.id, for_user_id: 1, message: 'Please call', matter_id: matter.id }, admin);
    await good('POST', `/api/callbacks/${callback.id}/attempt`, { result: 'No answer', retry_minutes: 30 }, staff);
    await good('POST', `/api/callbacks/${callback.id}/done`, { outcome: 'Resolved' }, staff);
    await good('GET', '/api/callers', {}, admin, { q: 'alex' });
    await good('POST', '/api/leave', { start_date: '2027-01-25', end_date: '2027-01-25', kind: 'Sick leave', note: 'Private note' }, staff);
    await good('POST', '/api/time/clock-in', {}, staff);
    await good('POST', '/api/time/log', { text: 'Reviewed matter title', task_ids: [task.id] }, staff);
    await good('GET', '/api/time/status', {}, staff);
    await good('POST', '/api/time/clock-out', { text: 'Finished work' }, staff);
    await good('GET', '/api/time/sheet', {}, admin, { from: '2026-10-01', to: '2026-10-31' });
    await good('GET', '/api/search', {}, admin, { q: 'case' });
    await good('GET', '/api/calendar/milestones', {}, admin);
    await good('GET', '/api/poll', {}, admin);
    await good('GET', '/api/settings', {}, admin);
    await good('GET', '/api/holidays', {}, admin);
    await db.withConnection(() => core.runJobs());
    await good('POST', '/api/logout', {}, staff);
    assert.equal((await call('GET', '/api/me', {}, staff)).status, 401);
  } finally { await db.close(); }
});
