-- Fresh TaskForce PostgreSQL structure: 24 tables and one admin.
-- No test records, checklist library, holidays, tasks or employee accounts are copied.
-- Execute the complete file in Supabase SQL Editor. Reruns preserve existing data.
-- taskforce_app is separate from the earlier taskforce_fresh_v1 schema.
-- The server's PostgreSQL adapter connects to taskforce_app using DATABASE_URL.
-- Run npm run setup:supabase to also prepare the upload metadata and private bucket.
-- This is an application account, not a Supabase Auth/dashboard account.
BEGIN;
CREATE SCHEMA IF NOT EXISTS taskforce_app;
REVOKE ALL ON SCHEMA taskforce_app FROM PUBLIC, anon, authenticated;
GRANT USAGE ON SCHEMA taskforce_app TO service_role;
SET LOCAL search_path = taskforce_app, pg_catalog;

CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  initials TEXT NOT NULL,
  color TEXT NOT NULL DEFAULT 'blue',
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL DEFAULT 'staff',
  active BIGINT NOT NULL DEFAULT 1,
  email_alerts BIGINT NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS'),
  claude_id TEXT,
  tax_access BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS sessions (
  token TEXT PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS matters (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL,
  type TEXT NOT NULL DEFAULT 'P',
  client TEXT NOT NULL DEFAULT '',
  address TEXT NOT NULL DEFAULT '',
  other_side TEXT NOT NULL DEFAULT '',
  settlement_date TEXT,
  finance_date TEXT,
  responsible_id BIGINT REFERENCES users(id),
  status TEXT NOT NULL DEFAULT 'active',
  notes TEXT NOT NULL DEFAULT '',
  gst_applies BIGINT NOT NULL DEFAULT 0,
  sdr_claimed BIGINT NOT NULL DEFAULT 0,
  readiness TEXT NOT NULL DEFAULT '{}',
  created_by BIGINT REFERENCES users(id),
  created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS'),
  updated_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS'),
  unconditional BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS matter_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  matter_id BIGINT NOT NULL REFERENCES matters(id) ON DELETE CASCADE,
  stage TEXT NOT NULL,
  parent_id BIGINT REFERENCES matter_items(id) ON DELETE CASCADE,
  title TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT '',
  person_id BIGINT REFERENCES users(id),
  date TEXT,
  value TEXT NOT NULL DEFAULT '',
  note TEXT NOT NULL DEFAULT '',
  position BIGINT NOT NULL DEFAULT 0,
  updated_by BIGINT,
  updated_at TEXT,
  ms TEXT,
  tpl_id BIGINT
);

CREATE TABLE IF NOT EXISTS checklist_templates (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  side TEXT NOT NULL,
  stage TEXT NOT NULL,
  parent_id BIGINT REFERENCES checklist_templates(id) ON DELETE CASCADE,
  title TEXT NOT NULL,
  position BIGINT NOT NULL DEFAULT 0,
  checklist_key TEXT,
  ms TEXT
);

CREATE TABLE IF NOT EXISTS tasks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  matter_id BIGINT REFERENCES matters(id) ON DELETE SET NULL,
  item_id BIGINT REFERENCES matter_items(id) ON DELETE SET NULL,
  assignee_id BIGINT REFERENCES users(id),
  created_by BIGINT REFERENCES users(id),
  due_date TEXT,
  priority TEXT NOT NULL DEFAULT 'normal',
  status TEXT NOT NULL DEFAULT 'todo',
  position DOUBLE PRECISION NOT NULL DEFAULT 0,
  offset_from TEXT,
  offset_days BIGINT,
  overdue_notified BIGINT NOT NULL DEFAULT 0,
  completed_at TEXT,
  created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS'),
  updated_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS'),
  due_time TEXT,
  repeat TEXT,
  repeat_until TEXT,
  series_id BIGINT,
  repeat_next_id BIGINT,
  duration BIGINT,
  auto_kind TEXT
);

CREATE TABLE IF NOT EXISTS checklist_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id BIGINT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
  text TEXT NOT NULL,
  done BIGINT NOT NULL DEFAULT 0,
  position BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS notes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id BIGINT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
  user_id BIGINT REFERENCES users(id),
  body TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE IF NOT EXISTS activity (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id BIGINT REFERENCES tasks(id) ON DELETE CASCADE,
  matter_id BIGINT REFERENCES matters(id) ON DELETE CASCADE,
  user_id BIGINT REFERENCES users(id),
  action TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE IF NOT EXISTS attachments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id BIGINT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
  filename TEXT NOT NULL,
  stored_name TEXT NOT NULL,
  mime TEXT NOT NULL DEFAULT 'application/octet-stream',
  size BIGINT NOT NULL DEFAULT 0,
  email_meta TEXT,
  uploaded_by BIGINT REFERENCES users(id),
  created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS'),
  parts_done BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS callbacks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  caller_name TEXT NOT NULL,
  phone TEXT NOT NULL DEFAULT '',
  email TEXT NOT NULL DEFAULT '',
  company TEXT NOT NULL DEFAULT '',
  matter_id BIGINT REFERENCES matters(id) ON DELETE SET NULL,
  message TEXT NOT NULL DEFAULT '',
  for_user_id BIGINT REFERENCES users(id),
  assignee_id BIGINT REFERENCES users(id),
  priority TEXT NOT NULL DEFAULT 'normal',
  due_at TEXT,
  status TEXT NOT NULL DEFAULT 'open',
  attempts BIGINT NOT NULL DEFAULT 0,
  outcome TEXT NOT NULL DEFAULT '',
  overdue_notified BIGINT NOT NULL DEFAULT 0,
  task_id BIGINT REFERENCES tasks(id) ON DELETE SET NULL,
  created_by BIGINT REFERENCES users(id),
  created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS'),
  updated_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS'),
  completed_at TEXT,
  completed_by BIGINT REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  task_id BIGINT REFERENCES tasks(id) ON DELETE CASCADE,
  matter_id BIGINT REFERENCES matters(id) ON DELETE CASCADE,
  kind TEXT NOT NULL,
  text TEXT NOT NULL,
  read BIGINT NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS'),
  callback_id BIGINT REFERENCES callbacks(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS checklists (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  key TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  position BIGINT NOT NULL DEFAULT 0,
  area TEXT NOT NULL DEFAULT 'conv'
);

CREATE TABLE IF NOT EXISTS checklist_stages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  checklist_key TEXT NOT NULL,
  key TEXT NOT NULL,
  label TEXT NOT NULL,
  from_kind TEXT NOT NULL DEFAULT 'opened',
  days BIGINT NOT NULL DEFAULT 0,
  when_text TEXT NOT NULL DEFAULT '',
  position BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS matter_stages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  matter_id BIGINT NOT NULL REFERENCES matters(id) ON DELETE CASCADE,
  key TEXT NOT NULL,
  label TEXT NOT NULL,
  from_kind TEXT NOT NULL DEFAULT 'opened',
  days BIGINT NOT NULL DEFAULT 0,
  when_text TEXT NOT NULL DEFAULT '',
  position BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS settings (
  key TEXT PRIMARY KEY,
  value TEXT
);

CREATE TABLE IF NOT EXISTS email_parts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  attachment_id BIGINT NOT NULL REFERENCES attachments(id) ON DELETE CASCADE,
  filename TEXT NOT NULL,
  mime TEXT NOT NULL DEFAULT 'application/octet-stream',
  size BIGINT NOT NULL DEFAULT 0,
  stored_name TEXT NOT NULL,
  position BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS file_tokens (
  token TEXT PRIMARY KEY,
  stored_name TEXT NOT NULL,
  filename TEXT NOT NULL,
  mime TEXT NOT NULL,
  expires_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS holidays (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  date TEXT NOT NULL,
  name TEXT NOT NULL,
  part_from TEXT,
  source TEXT NOT NULL DEFAULT 'act',
  created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE IF NOT EXISTS leave (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  start_date TEXT NOT NULL,
  end_date TEXT NOT NULL,
  kind TEXT NOT NULL DEFAULT 'Annual leave',
  part TEXT NOT NULL DEFAULT '',
  note TEXT NOT NULL DEFAULT '',
  created_by BIGINT REFERENCES users(id),
  created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE IF NOT EXISTS time_entries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  clock_in TEXT NOT NULL,
  clock_out TEXT,
  note TEXT NOT NULL DEFAULT '',
  edited_by BIGINT REFERENCES users(id),
  created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE IF NOT EXISTS work_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  entry_id BIGINT REFERENCES time_entries(id) ON DELETE SET NULL,
  at TEXT NOT NULL,
  since TEXT,
  text TEXT NOT NULL,
  task_ids TEXT NOT NULL DEFAULT '',
  kind TEXT NOT NULL DEFAULT 'checkin',
  created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE IF NOT EXISTS login_codes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  code_hash TEXT NOT NULL,
  purpose TEXT NOT NULL DEFAULT 'login',
  expires_at TEXT NOT NULL,
  tries BIGINT NOT NULL DEFAULT 0,
  used BIGINT NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE IF NOT EXISTS callback_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  callback_id BIGINT NOT NULL REFERENCES callbacks(id) ON DELETE CASCADE,
  user_id BIGINT REFERENCES users(id),
  kind TEXT NOT NULL,
  text TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS')
);

CREATE INDEX IF NOT EXISTS idx_items_matter ON matter_items(matter_id);

CREATE INDEX IF NOT EXISTS idx_tasks_status ON tasks(status);

CREATE INDEX IF NOT EXISTS idx_tasks_matter ON tasks(matter_id);

CREATE INDEX IF NOT EXISTS idx_notif_user ON notifications(user_id, read);

CREATE INDEX IF NOT EXISTS idx_mstages ON matter_stages(matter_id);

CREATE INDEX IF NOT EXISTS idx_parts_att ON email_parts(attachment_id);

CREATE INDEX IF NOT EXISTS idx_cb_status ON callbacks(status, assignee_id);

CREATE INDEX IF NOT EXISTS idx_hol_date ON holidays(date);

CREATE INDEX IF NOT EXISTS idx_leave_dates ON leave(start_date, end_date);

CREATE INDEX IF NOT EXISTS idx_time_user ON time_entries(user_id, clock_in);

CREATE INDEX IF NOT EXISTS idx_wlog_user ON work_logs(user_id, at);

CREATE UNIQUE INDEX IF NOT EXISTS users_email_ci ON users(lower(email));

CREATE UNIQUE INDEX IF NOT EXISTS matters_code_type_ci ON matters(lower(code), type);

